-- Norns (timeline agent): rules derived from Thor's extractions, their dated instances,
-- the simulated clock, timeline snapshots for the dashboard, worst-case exposure items and
-- the plain-English writeups. Everything here is recomputable from the other tables
-- (source_kind 'analysis'); nothing in it is read from a contract directly.

create table if not exists obligation_rules (
    rule_id        text primary key,               -- e.g. "A1:payment:monthly_fee@2026-08-01"
    contract       text not null,                  -- root contract of the family (A1, B1)
    doc_id         text not null,                  -- document whose clause states the term (A1, A2, A3, STD ...)
    kind           text not null check (kind in ('payment','notice','renewal','report','cure','penalty_trigger','credit')),
    name           text not null,
    payer          text,
    payee          text,
    anchor         text not null,                  -- invoice_date | term_end | month_end | due_date | fixed | event:<type>
    anchor_date    date,
    offset_amount  integer,
    offset_unit    text,                           -- days | hours | months
    offset_direction text,                         -- after | before
    day_type       text check (day_type in ('business','calendar','unspecified')),
    recurrence     jsonb,
    amount         numeric(14, 2),
    formula        text,
    currency       text,
    escalations    jsonb not null default '[]'::jsonb,
    caps           jsonb not null default '[]'::jsonb,
    conditions     jsonb not null default '[]'::jsonb,
    valid_from     date,
    valid_to       date,                           -- exclusive
    citations      jsonb not null default '[]'::jsonb,   -- Thor extraction ids + clause quotes
    flags          jsonb not null default '[]'::jsonb,
    source_kind    text not null default 'analysis',
    built_at       timestamptz not null
);
create index if not exists ix_obligation_rules_contract on obligation_rules(contract, kind);

create table if not exists obligation_instances (
    id             bigint generated by default as identity primary key,
    as_of          date not null,
    instance_key   text not null,
    rule_id        text not null,
    contract       text not null,
    kind           text not null,
    name           text not null,
    period         text,                           -- e.g. "2027-04" for a monthly fee
    anchor_date    date,
    due_date       date,
    due_date_calendar date,
    due_date_business date,
    day_type       text,
    amount         numeric(14, 2),
    currency       text,
    payer          text,
    payee          text,
    status         text not null check (status in ('paid_on_time','paid_late','partial','unpaid','upcoming','met','missed','triggered')),
    paid_amount    numeric(14, 2),
    paid_date      date,
    ledger_lines   jsonb not null default '[]'::jsonb,
    days_remaining integer,
    severity       text,
    flags          jsonb not null default '[]'::jsonb,
    citations      jsonb not null default '[]'::jsonb,
    unique (as_of, instance_key)
);
create index if not exists ix_obligation_instances_asof on obligation_instances(as_of, contract);

-- A single row: where the simulated clock stands.
create table if not exists clock_state (
    id             integer primary key check (id = 1),
    current_as_of  date not null,
    updated_at     timestamptz not null
);

create table if not exists clock_history (
    id             bigint generated by default as identity primary key,
    ts             timestamptz not null,
    action         text not null,                  -- set | checkpoint | advance | play
    from_as_of     date,
    to_as_of       date not null,
    note           text
);

create table if not exists timeline_snapshots (
    id             bigint generated by default as identity primary key,
    as_of          date not null,
    created_at     timestamptz not null,
    summary        jsonb not null default '{}'::jsonb,
    chart_data     jsonb not null default '{}'::jsonb
);
create index if not exists ix_timeline_snapshots_asof on timeline_snapshots(as_of, id);

create table if not exists exposure_items (
    id             bigint generated by default as identity primary key,
    as_of          date not null,
    scenario       text not null check (scenario in ('worst_case','on_time')),
    contract       text not null,
    category       text not null,
    amount         numeric(14, 2),                 -- null when the contract gives no number
    status         text not null check (status in ('quantified','unquantified')),
    accrues_on     date,
    description    text not null,
    formula        text,
    inputs         jsonb not null default '{}'::jsonb,
    citations      jsonb not null default '[]'::jsonb,
    source_kind    text not null default 'analysis',
    created_at     timestamptz not null
);
create index if not exists ix_exposure_items_asof on exposure_items(as_of, scenario);

create table if not exists writeups (
    id             bigint generated by default as identity primary key,
    as_of          date not null,
    label          text not null,                  -- "AI-generated analysis" | "Template writeup (LLM unavailable)" ...
    generated_by   text not null check (generated_by in ('llm','template')),
    text           text not null,
    model          text,
    prompt_hash    text,
    check_passed   boolean,
    meta           jsonb not null default '{}'::jsonb,
    created_at     timestamptz not null
);
create index if not exists ix_writeups_asof on writeups(as_of, id);

alter table obligation_rules     enable row level security;
alter table obligation_instances enable row level security;
alter table clock_state          enable row level security;
alter table clock_history        enable row level security;
alter table timeline_snapshots   enable row level security;
alter table exposure_items       enable row level security;
alter table writeups             enable row level security;
