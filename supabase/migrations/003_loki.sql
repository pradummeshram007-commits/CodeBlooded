-- Loki (adversarial review agent): findings from reading each contract as the
-- counterparty's lawyer. One set per (doc_id, as_of); a re-run replaces it. Rejected
-- findings are kept with the reason the code checks gave. Derived data (source_kind
-- 'analysis'): citations point at clauses, impact is copied from Norns' exposure_items.

create table if not exists loki_findings (
    id                bigint generated by default as identity primary key,
    doc_id            text not null,                  -- the reviewed document (A1, A2, ...)
    as_of             date not null,
    run_id            text,
    model             text,
    source_kind       text not null default 'analysis',
    type              text check (type in ('ambiguity','one_sided','hidden_liability')),   -- null only when rejected as invalid
    title             text not null,
    exploited_by      text,                           -- the counterparty's name
    citations         jsonb not null default '[]'::jsonb,   -- {doc_id, clause_id, quote, verified, char_start, char_end, ...}
    readings          jsonb not null default '[]'::jsonb,   -- ambiguity only: {reading, counterparty_argues}
    attack_path       jsonb not null default '[]'::jsonb,   -- 2-5 steps
    severity          text check (severity in ('critical','high','medium','low')),
    severity_reason   text not null default '',
    likelihood        text check (likelihood in ('high','medium','low')),
    likelihood_reason text not null default '',
    confidence        double precision not null check (confidence >= 0 and confidence <= 1),
    impact            jsonb not null default '"unquantified"'::jsonb,   -- {exposure_item_id, amount, ...} or "unquantified"
    status            text not null check (status in ('accepted','rejected')),
    rejection_reason  text,
    part              text,                           -- review part that produced it, e.g. "2/3"
    rank              integer not null default 0,
    notes             jsonb not null default '[]'::jsonb,
    created_at        timestamptz not null
);
create index if not exists ix_loki_findings_doc on loki_findings(doc_id, as_of, status);

alter table loki_findings enable row level security;
