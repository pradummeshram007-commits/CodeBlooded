-- Heimdall (event monitoring + task board). heimdall_events: every line of a released
-- event drop as Heimdall saw it on one clock date (as_of), with its mapping to contracts and
-- clauses, its Norns fact and the worst-case exposure before / after that fact.
-- heimdall_alerts: severity-rated alerts for the clock date. heimdall_tasks: the task board,
-- one card per Norns obligation instance near the clock date, with the team's status tags.

create table if not exists heimdall_events (
    id               bigint generated by default as identity primary key,
    as_of            date not null,                 -- the clock date of the run
    drop_name        text not null,                 -- drop1 | drop2
    line_no          integer not null,              -- line in the drop file
    event_id         text,                          -- E-01 ...; null when the line could not be parsed
    raw              text not null,
    event_date       date,
    channel          text,
    sender           text,
    recipient        text,
    subject          text,
    status           text not null check (status in ('mapped','unmapped','noise','unparseable')),
    status_reason    text,
    type             text,
    doc_ids          jsonb not null default '[]'::jsonb,
    clause_ids       jsonb not null default '[]'::jsonb,
    fact             jsonb,                         -- payment_made | outage | notice_sent | other
    is_noise         boolean not null default false,
    noise_reason     text,
    mapped_by        text check (mapped_by in ('code','llm')),
    confidence       double precision,
    potential_breach boolean not null default false,
    breach_reason    text,
    exposure         jsonb not null default '{}'::jsonb,   -- {before, after, delta, by_contract, changes}
    run_id           text,
    created_at       timestamptz not null,
    unique (as_of, drop_name, line_no)
);

create table if not exists heimdall_alerts (
    id               bigint generated by default as identity primary key,
    as_of            date not null,
    alert_key        text not null,                 -- contract|clause|kind|due date
    severity         text not null check (severity in ('critical','high','medium','low')),
    kind             text not null,
    contract         text,
    clause_id        text,
    due_date         date,
    message          text not null,
    citation         jsonb not null default '{}'::jsonb,   -- {doc_id, clause_id, quote}
    source           text not null check (source in ('norns','event')),
    event_id         text,
    instance_key     text,
    run_id           text,
    created_at       timestamptz not null,
    unique (as_of, alert_key)
);

create table if not exists heimdall_tasks (
    as_of            date not null,
    task_id          text not null,                 -- the Norns obligation instance key
    title            text not null,
    contract         text not null,
    kind             text not null,
    period           text,
    due_date         date,
    amount           numeric(14, 2),
    citation         jsonb not null default '{}'::jsonb,
    status           text not null check (status in ('Not Complete','In Progress','Completed')),
    status_source    text not null check (status_source in ('norns','user')),
    norns_status     text,
    fact             jsonb,                         -- the user's payment_made fact while Completed by the user
    payer            text,
    payee            text,
    updated_at       timestamptz not null,
    primary key (as_of, task_id)
);

alter table heimdall_events enable row level security;
alter table heimdall_alerts enable row level security;
alter table heimdall_tasks  enable row level security;
