-- Odin (orchestrator): one row per pipeline run, THOR -> NORNS -> LOKI -> HEIMDALL for one
-- document on one clock date. The row is saved as each stage starts and ends, so the web app
-- can show the run live; stages holds every agent's status, numbers and reason.

create table if not exists pipeline_runs (
    id               bigint generated by default as identity primary key,
    run_id           text not null unique,
    doc_id           text not null,                 -- the document the run is for (uploaded or chosen)
    as_of            date not null,                 -- the clock date NORNS, LOKI and HEIMDALL work on
    source           text not null check (source in ('upload','manual')),
    status           text not null check (status in ('queued','running','complete','partial','failed','interrupted')),
    current_stage    text,
    stages           jsonb not null default '[]'::jsonb,   -- {name, status, summary, reason, details, llm_calls, ...}
    plan             jsonb not null default '{}'::jsonb,   -- workstream, root contract, LOKI's documents, drops
    options          jsonb not null default '{}'::jsonb,
    reason           text,                          -- why the run is not complete
    llm              jsonb not null default '{}'::jsonb,   -- totals across agents
    created_at       timestamptz not null,
    started_at       timestamptz,
    finished_at      timestamptz,
    updated_at       timestamptz not null
);
create index if not exists ix_pipeline_runs_doc on pipeline_runs(doc_id, created_at);

alter table pipeline_runs enable row level security;
