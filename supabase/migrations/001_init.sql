-- Odin shared state on Supabase Postgres.
--
-- One table per StateStore concern; mirrors the SQLite schema in odin/state/store.py
-- (tests/test_migrations.py checks that both define the same tables and columns).
-- Applied by scripts/db_migrate.py, which records it in schema_migrations. Every
-- statement is idempotent (IF NOT EXISTS), so a re-run is harmless.
--
-- Row level security is enabled on every table with no policies: the tables are not
-- reachable through Supabase's public Data API (anon / authenticated keys). Odin connects
-- server-side as the table owner, which RLS does not restrict.

create table if not exists meta (
    key   text primary key,
    value text
);

-- Contracts. text is the full extracted text; every clause offset indexes into it.
create table if not exists documents (
    doc_id            text primary key,
    title             text not null,
    text_title        text,
    path              text not null,
    sha256            text not null,
    kind              text not null check (kind in ('contract','standard_terms','amendment','addendum')),
    status            text not null default 'pending' check (status in ('pending','extracting','complete','partial','failed')),
    status_reason     text,
    coverage          double precision,
    external_id       text,
    source            text not null default 'bundle',
    extracted_sha256  text,
    text              text,
    text_source       text check (text_source in ('txt','pdf_extracted')),
    parse_status      text check (parse_status in ('parsed','fallback','unparseable')),
    storage_path      text,                 -- viewable original in bucket "contracts": {doc_id}/{sha256}/{filename}
    original_filename text,
    mime_type         text,
    uploaded_at       timestamptz,
    ingested_at       timestamptz not null,
    updated_at        timestamptz not null
);
create index if not exists ix_documents_sha on documents(sha256);

-- Every stored file of a document: the .txt text source and the .pdf original are one document.
create table if not exists document_files (
    id                bigint generated by default as identity primary key,
    doc_id            text not null references documents(doc_id),
    role              text not null check (role in ('text_source','original','attachment')),
    sha256            text not null,
    storage_path      text not null,
    original_filename text not null,
    mime_type         text not null,
    size_bytes        bigint not null,
    similarity        double precision,     -- PDF text vs the .txt, when both exist
    uploaded_at       timestamptz not null,
    unique (doc_id, sha256)
);
create index if not exists ix_document_files_sha on document_files(sha256);

create table if not exists clauses (
    clause_id  text primary key,
    doc_id     text not null references documents(doc_id),
    number     text not null,
    ref        text not null,
    heading    text,
    text       text not null,
    char_start integer not null,
    char_end   integer not null,
    level      integer not null default 1,
    parent_id  text,
    ordinal    integer not null default 0,
    kind       text not null default 'clause'
);
create index if not exists ix_clauses_doc on clauses(doc_id, ordinal);

create table if not exists extractions (
    id            bigint generated by default as identity primary key,
    doc_id        text not null references documents(doc_id),
    field_type    text not null,
    field_key     text not null,
    value         jsonb,
    readings      jsonb not null default '[]'::jsonb,
    raw_text      text not null default '',
    confidence    double precision not null check (confidence >= 0 and confidence <= 1),
    status        text not null check (status in ('extracted','ambiguous','missing','contradictory')),
    source_kind   text not null default 'sourced' check (source_kind in ('sourced','analysis')),
    agent         text not null,
    version       integer not null default 1,
    is_current    boolean not null default true,
    supersedes_id bigint references extractions(id),
    run_id        text,
    notes         text,
    created_at    timestamptz not null
);
create index if not exists ix_extractions_doc on extractions(doc_id, is_current);
create index if not exists ix_extractions_key on extractions(doc_id, agent, field_key, version);

create table if not exists citations (
    id            bigint generated by default as identity primary key,
    extraction_id bigint references extractions(id),
    doc_id        text not null,
    clause_id     text,
    clause_ref    text,
    quote         text not null,
    llm_quote     text,
    llm_clause_id text,
    char_start    integer,
    char_end      integer,
    verified      boolean not null default false,
    match_method  text not null default 'none',
    source_type   text not null default 'clause'
);
create index if not exists ix_citations_extraction on citations(extraction_id);
create index if not exists ix_citations_clause on citations(clause_id);

create table if not exists flags (
    id                bigint generated by default as identity primary key,
    doc_id            text,
    clause_id         text,
    type              text not null check (type in ('ambiguous','missing','contradictory','unparseable','cross_reference','unverified_citation')),
    description       text not null,
    raised_by         text not null,
    extraction_id     bigint references extractions(id),
    evidence          text,
    evidence_verified boolean,
    status            text not null default 'open' check (status in ('open','resolved','superseded')),
    run_id            text,
    created_at        timestamptz not null
);
create index if not exists ix_flags_doc on flags(doc_id, status);

create table if not exists doc_relations (
    id            bigint generated by default as identity primary key,
    from_doc      text not null,
    to_doc        text not null,
    type          text not null check (type in ('incorporates','amends','supersedes','references','conflicts')),
    clause_id     text,
    citation      jsonb not null default '{}'::jsonb,
    extraction_id bigint references extractions(id),
    raised_by     text not null,
    verified      boolean not null default false,
    created_at    timestamptz not null
);
create unique index if not exists ux_relations on doc_relations(from_doc, to_doc, type, coalesce(clause_id, ''), raised_by);

create table if not exists messages (
    id            bigint generated by default as identity primary key,
    from_agent    text not null,
    to_agent      text not null,
    type          text not null check (type in ('clarification_request','clarification_response','claim','verification','ruling','alert')),
    payload       jsonb not null default '{}'::jsonb,
    status        text not null default 'pending' check (status in ('pending','processing','done','failed')),
    in_reply_to   bigint references messages(id),
    workstream_id text,
    created_at    timestamptz not null,
    updated_at    timestamptz not null
);
create index if not exists ix_messages_inbox on messages(to_agent, status, type);

create table if not exists workstreams (
    id           text primary key,
    scope        text not null,
    members      jsonb not null default '[]'::jsonb,
    agent_status jsonb not null default '{}'::jsonb,
    notes        text,
    updated_at   timestamptz not null
);

create table if not exists trace (
    id          bigint generated by default as identity primary key,
    ts          timestamptz not null,
    run_id      text,
    agent       text not null,
    action      text not null,
    input_ref   text,
    output_ref  text,
    tokens      integer not null default 0,
    duration_ms integer not null default 0,
    error       text,
    meta        jsonb not null default '{}'::jsonb
);
create index if not exists ix_trace_run on trace(run_id, agent);

-- Inputs for the later agents (Norns / Heimdall / Tyr).
create table if not exists resources (
    path         text primary key,
    kind         text not null,
    title        text,
    sha256       text not null,
    storage_path text,
    mime_type    text,
    size_bytes   bigint,
    text         text,
    loaded_at    timestamptz not null
);

-- Filled by Heimdall drop by drop; seeding only stores the raw .jsonl files in Storage.
create table if not exists events (
    id           bigint generated by default as identity primary key,
    event_id     text,
    drop_name    text not null,
    line_no      integer not null,
    timestamp    text,                      -- as written; a malformed line keeps its raw text
    channel      text,
    from_party   text,
    to_party     text,
    subject      text,
    body         text,
    raw          text not null,
    parse_error  text,
    processed_by jsonb not null default '{}'::jsonb
);
create unique index if not exists ux_events_line on events(drop_name, line_no);

create table if not exists ledger_entries (
    id          bigint generated by default as identity primary key,
    line_no     integer not null unique,
    date        date not null,
    from_party  text not null,
    to_party    text not null,
    amount      numeric(14, 2) not null,
    reference   text not null,
    status      text not null,
    contract_id text
);

create table if not exists holidays (
    date        date not null,
    name        text not null,
    observed_by text not null,
    primary key (date, observed_by)
);

create table if not exists clock_checkpoints (
    idx   integer primary key,
    date  date not null,
    label text not null
);

alter table meta              enable row level security;
alter table documents         enable row level security;
alter table document_files    enable row level security;
alter table clauses           enable row level security;
alter table extractions       enable row level security;
alter table citations         enable row level security;
alter table flags             enable row level security;
alter table doc_relations     enable row level security;
alter table messages          enable row level security;
alter table workstreams       enable row level security;
alter table trace             enable row level security;
alter table resources         enable row level security;
alter table events            enable row level security;
alter table ledger_entries    enable row level security;
alter table holidays          enable row level security;
alter table clock_checkpoints enable row level security;
